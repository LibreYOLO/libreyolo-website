'use client'

import { useEffect, useRef, useState } from 'react'
import SplatViewer from './SplatViewer'
import objects from '@/data/idol-vs-gallery.json'

/*
 * Speridlabs Idol, TripoSplat and TRELLIS on the same images: pick an object,
 * then a model. Each object loads (4 to 13 MB) only when it is picked.
 */

const MODELS = ['speridlabs-idol', 'triposplat', 'trellis']
const linkClass = 'text-libre-700 underline-offset-2 hover:underline dark:text-libre-400'

export default function IdolVsGallery() {
  const [current, setCurrent] = useState(0)
  const [model, setModel] = useState(MODELS[0])
  const [near, setNear] = useState(false)
  const rootRef = useRef(null)

  useEffect(() => {
    const observer = new IntersectionObserver(([entry]) => {
      if (entry.isIntersecting) {
        setNear(true)
        observer.disconnect()
      }
    }, { rootMargin: '300px' })
    observer.observe(rootRef.current)
    return () => observer.disconnect()
  }, [])

  const object = objects[current]
  const variant = object.models[model]
  const byline = object.artist ? `${object.title}, ${object.artist}` : object.title
  const credited = objects.filter((item) => item.photo_credit && item.photo_credit.license)

  return (
    <div ref={rootRef} className="not-prose my-8">
      <div className="mb-3 flex flex-wrap gap-2" role="group" aria-label="Model">
        {MODELS.map((key) => (
          <button
            key={key}
            type="button"
            onClick={() => { setNear(true); setModel(key) }}
            aria-pressed={key === model}
            className={`rounded-full border px-3.5 py-1.5 text-[13px] font-medium transition-colors ${
              key === model
                ? 'border-libre-500 bg-libre-500 text-white'
                : 'border-surface-200 text-surface-700 hover:border-libre-400 dark:border-white/[0.12] dark:text-surface-300'
            }`}
          >
            {object.models[key].label}
          </button>
        ))}
      </div>

      <div className="relative aspect-[4/3] w-full overflow-hidden rounded-lg border border-surface-200 bg-[#0b0b0d] dark:border-white/[0.09]">
        <SplatViewer
          key={`${object.slug}-${model}`}
          src={variant.file}
          camera={variant.camera}
          active={near}
          label={`3D object of ${byline}, generated by ${variant.label}`}
        />
        <div className="pointer-events-none absolute left-3 top-3 max-w-[70%] text-white">
          <div className="text-[15px] font-semibold leading-tight">{variant.label}</div>
          <div className="text-[13px] text-white/70">{byline}</div>
          <div className="mt-1 text-[12px] text-white/55">
            {variant.gaussians.toLocaleString('en-US')} Gaussians, seed 0, 50 steps
          </div>
        </div>
        <img
          src={object.photo}
          alt={`The image ${byline} was generated from`}
          className="pointer-events-none absolute bottom-3 left-3 w-[22%] max-w-[150px] rounded border border-white/30"
        />
        <div className="pointer-events-none absolute bottom-3 right-3 hidden text-right text-[11px] text-white/50 sm:block">
          Drag to turn, right-drag to pan<br />Pinch or ctrl + scroll to zoom, double-click to reset
        </div>
      </div>

      <div className="mt-3 grid grid-cols-3 gap-2 sm:grid-cols-6">
        {objects.map((item, i) => (
          <button
            key={item.slug}
            type="button"
            onClick={() => { setNear(true); setCurrent(i) }}
            aria-pressed={i === current}
            title={item.artist ? `${item.title}, ${item.artist}` : item.title}
            className={`group relative overflow-hidden rounded border text-left transition-colors ${
              i === current
                ? 'border-libre-500 ring-2 ring-libre-500/40'
                : 'border-surface-200 hover:border-libre-400 dark:border-white/[0.09]'
            }`}
          >
            <img src={item.photo} alt={item.title} loading="lazy" className="block aspect-square w-full object-cover" />
            <span className="absolute inset-x-0 bottom-0 bg-black/60 px-1.5 py-1 text-[11px] leading-tight text-white">
              {item.title}
            </span>
          </button>
        ))}
      </div>

      <p className="mt-3 text-[12.5px] leading-[1.55] text-surface-500 dark:text-surface-500">
        Each object was generated in LibreYOLO from the one image shown with it, with the same seed and 50
        steps for every model. The galleon comes from a frame of the{' '}
        <a href="https://elkano.dev" target="_blank" rel="noopener noreferrer" className={linkClass}>elkano.dev</a>{' '}
        video; the egg chair, panda and microscope images come from the{' '}
        <a href="https://github.com/speridlabs/idol-sdk" target="_blank" rel="noopener noreferrer" className={linkClass}>Idol SDK</a>{' '}
        demo (Apache-2.0). Photos via Wikimedia Commons:{' '}
        {credited.map((item, i) => (
          <span key={item.slug}>
            {item.title} by{' '}
            <a href={item.photo_credit.url} target="_blank" rel="noopener noreferrer" className={linkClass}>
              {item.photo_credit.author}, {item.photo_credit.license}
            </a>
            {i < credited.length - 1 ? '; ' : '.'}
          </span>
        ))}{' '}
        Objects made from a CC BY-SA photo are shared under CC BY-SA 4.0.
      </p>
    </div>
  )
}
