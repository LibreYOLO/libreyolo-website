'use client'

import { useEffect, useRef, useState } from 'react'
import SplatViewer from './SplatViewer'
import objects from '@/data/idol-gallery.json'

/*
 * Speridlabs Idol results, each generated from the one photo shown with it.
 * The first object loads when the gallery scrolls into view; picking a photo
 * loads that object (about 4 MB each) into the same viewer.
 */

const linkClass = 'text-libre-700 underline-offset-2 hover:underline dark:text-libre-400'

function credit(photo) {
  return `${photo.author}, ${photo.license}`
}

export default function IdolGallery() {
  const [current, setCurrent] = useState(0)
  const [near, setNear] = useState(false)
  const rootRef = useRef(null)

  useEffect(() => {
    const observer = new IntersectionObserver(([entry]) => {
      if (entry.isIntersecting) {
        setNear(true)
        observer.disconnect()
      }
    }, { rootMargin: '300px' })
    observer.observe(rootRef.current)
    return () => observer.disconnect()
  }, [])

  const object = objects[current]
  const byline = object.artist ? `${object.title}, ${object.artist}` : object.title

  return (
    <div ref={rootRef} className="not-prose my-8">
      <div className="relative aspect-[4/3] w-full overflow-hidden rounded-lg border border-surface-200 bg-[#0b0b0d] dark:border-white/[0.09]">
        <SplatViewer src={object.file} camera={object.camera} active={near} label={`3D object of ${byline}, generated by Speridlabs Idol`} />
        <div className="pointer-events-none absolute left-3 top-3 max-w-[70%] text-white">
          <div className="text-[15px] font-semibold leading-tight">{object.title}</div>
          {object.artist && <div className="text-[13px] text-white/70">{object.artist}</div>}
          <div className="mt-1 text-[12px] text-white/55">
            {object.gaussians.toLocaleString('en-US')} Gaussians, seed {object.seed}, {object.seconds} s on an H100
          </div>
        </div>
        <img
          src={object.photo}
          alt={`The photo of ${byline} the object was generated from`}
          className="pointer-events-none absolute bottom-3 left-3 w-[22%] max-w-[150px] rounded border border-white/30"
        />
        <div className="pointer-events-none absolute bottom-3 right-3 hidden text-right text-[11px] text-white/50 sm:block">
          Drag to turn, right-drag to pan<br />Pinch or ctrl + scroll to zoom, double-click to reset
        </div>
      </div>

      <div className="mt-3 grid grid-cols-4 gap-2 sm:grid-cols-6">
        {objects.map((item, i) => (
          <button
            key={item.slug}
            type="button"
            onClick={() => { setNear(true); setCurrent(i) }}
            aria-pressed={i === current}
            title={item.artist ? `${item.title}, ${item.artist}` : item.title}
            className={`group relative overflow-hidden rounded border text-left transition-colors ${
              i === current
                ? 'border-libre-500 ring-2 ring-libre-500/40'
                : 'border-surface-200 hover:border-libre-400 dark:border-white/[0.09]'
            }`}
          >
            <img src={item.photo} alt={item.title} loading="lazy" className="block aspect-square w-full object-cover" />
            <span className="absolute inset-x-0 bottom-0 bg-black/60 px-1.5 py-1 text-[11px] leading-tight text-white">
              {item.title}
            </span>
          </button>
        ))}
      </div>

      <p className="mt-3 text-[12.5px] leading-[1.55] text-surface-500 dark:text-surface-500">
        Each object was generated by Speridlabs Idol in LibreYOLO from the one photo shown with it, with{' '}
        <code>mode=&quot;real&quot;</code> and the default settings, then stored at about 4 MB for the web. The
        objects are shared under CC BY-SA 4.0. Photos via Wikimedia Commons:{' '}
        {objects.map((item, i) => (
          <span key={item.slug}>
            {item.title} by{' '}
            <a href={item.photo_credit.url} target="_blank" rel="noopener noreferrer" className={linkClass}>
              {credit(item.photo_credit)}
            </a>
            {i < objects.length - 1 ? '; ' : '.'}
          </span>
        ))}
      </p>
    </div>
  )
}
